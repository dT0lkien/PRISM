/* Список изменений по версиям.
   После обновления Prism один раз показывает окно с записью для текущей
   версии. Новая версия без записи здесь окно не покажет — порядок выпуска
   описан в README, раздел «Обновления». */

export interface ReleaseNote {
  version: string
  /** ISO-дата релиза, показывается рядом с номером версии */
  date: string
  /** Короткие пункты «что изменилось» — по одной мысли на строку */
  items: string[]
}

export const CHANGELOG: ReleaseNote[] = [
  {
    version: '1.5.0',
    date: '2026-08-28',
    items: [
      'Новая тема «Хром»: жидкий металл, чёрный фон и звёзды нулевых',
      'После обновления Prism один раз показывает, что изменилось',
      'Заголовки и подписи в «Хроме» набраны хромированным градиентом и моноширинным шрифтом'
    ]
  },
  {
    version: '1.4.1',
    date: '2026-08-27',
    items: [
      'Закрыта уязвимость: подписка больше не может подсунуть ядру произвольную программу',
      'Поддержка macOS: TUN работает через привилегированный помощник',
      'Сборки .dmg для Apple Silicon и Intel собираются в CI'
    ]
  }
]

/** Запись для версии или undefined, если её не описали */
export function releaseNote(version: string): ReleaseNote | undefined {
  return CHANGELOG.find((r) => r.version === version)
}
